"""Generate the three TikZ sources for the elementary row operation figures.

Run from the project root, then render each source with
figures/00-shared/academic-drawing/render_tikz.py.
Data: A=[1 2;3 4;5 6]; operations r1<->r3, r2<-2r2, r3<-r3-5r1.
"""
from pathlib import Path

D = Path(__file__).resolve().parent
B, G, Y, W = "FigureBlueFill", "FigureGreenFill", "FigureYellowFill", "white"
NOTE = r"\FigureNoteFont\fontsize{7.5pt}{9pt}\selectfont"


def grid(x0, top, M, fills, c=6):
    out = []
    for i, row in enumerate(M):
        for j, v in enumerate(row):
            y = top - (i + 1) * c
            out.append(f"\\draw[draw=FigureGrid,line width=0.4pt,fill={fills[i][j]}] ({x0+j*c},{y}) rectangle ++({c},{c});")
            out.append(f"\\node[text=FigureInk] at ({x0+j*c+c/2},{y+c/2}) {{${v}$}};")
    w, h = len(M[0]) * c, len(M) * c
    for a, b in ((x0 + 1.2, x0 - 0.6), (x0 + w - 1.2, x0 + w + 0.6)):
        out.append(f"\\draw[FigureStroke,line width=0.6pt] ({a},{top+0.6})--({b},{top+0.6})--({b},{top-h-0.6})--({a},{top-h-0.6});")
    return out


def rows(cols, spec):
    return [[spec.get(i, W)] * cols for i in range(3)]


def fig(name, A, FA, R, FR, E, FE, op, opmath, note):
    top = 20
    L = ["% " + note, "% Generated by generate.py; edit the generator and re-render.",
         r"\begin{tikzpicture}[x=1mm,y=1mm,font=\figurefont\fontsize{8pt}{9.6pt}\selectfont]",
         r"\path[use as bounding box] (-5,-5) rectangle (103,27);"]
    for i in range(3):
        L.append(f"\\node[text=FigureMuted] at (-1.5,{top-3-6*i}) {{$r_{i+1}$}};")
    L.append(f"\\node[text=FigureInk] at (9,{top+4.5}) {{$\\bm A$}};")
    L += grid(3, top, A, FA)
    L.append(f"\\draw[-{{Stealth[length=2.2mm]}},FigureStroke,line width=0.75pt] (19,{top-9})--(52,{top-9});")
    L.append(f"\\node[text=FigureInk,above] at (35.5,{top-8.5}) {{{op}}};")
    L.append(f"\\node[text=FigureInk,below] at (35.5,{top-9.5}) {{${opmath}$}};")
    L.append(f"\\node[text=FigureInk] at (61,{top+4.5}) {{$\\bm E\\bm A$}};")
    L += grid(55, top, R, FR)
    L.append(f"\\draw[FigureGrid,line width=0.6pt,dashed] (73.5,{top+6})--(73.5,{top-22});")
    L.append(f"\\node[text=FigureInk] at (89,{top+4.5}) {{初等矩阵$\\bm E$}};")
    L += grid(80, top, E, FE)
    L.append(f"\\node[text=FigureMuted,font={NOTE}] at (89,{top-22.5}) {{对$\\bm I_3$作同一变换}};")
    L.append(r"\end{tikzpicture}")
    (D / f"{name}.tex").write_text("\n".join(L) + "\n")


A = [[1, 2], [3, 4], [5, 6]]
fig("row-swap", A, rows(2, {0: B, 2: G}), [[5, 6], [3, 4], [1, 2]], rows(2, {0: G, 2: B}),
    [[0, 0, 1], [0, 1, 0], [1, 0, 0]], rows(3, {0: G, 2: B}), "交换第1、3行", r"r_1\leftrightarrow r_3",
    "Swap rows 1 and 3 of A; E swaps rows 1 and 3 of I3 (row colours follow the moved rows).")
fig("row-scale", A, rows(2, {1: Y}), [[1, 2], [6, 8], [5, 6]], rows(2, {1: Y}),
    [[1, 0, 0], [0, 2, 0], [0, 0, 1]], rows(3, {1: Y}), "第2行乘以2", r"r_2\leftarrow 2r_2",
    "Multiply row 2 of A by 2; E=diag(1,2,1).")
FE = [[W] * 3 for _ in range(3)]
FE[0] = [B] * 3
FE[2][0] = Y
fig("row-replace", A, rows(2, {0: B, 2: Y}), [[1, 2], [3, 4], [0, -4]], [[B, B], [W, W], [G, Y]],
    [[1, 0, 0], [0, 1, 0], [-5, 0, 1]], FE, "第3行加上第1行的$-5$倍", r"r_3\leftarrow r_3-5r_1",
    "Add -5 times row 1 to row 3 of A, making the (3,1) entry zero; E=I3 with (3,1)=-5.")
