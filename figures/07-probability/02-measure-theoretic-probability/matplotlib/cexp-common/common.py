def cond_mean(Z, key):
    """E[Z | partition given by key(x, y)] on the sensor table; None on null groups."""
    out = np.full((3, 3), np.nan)
    for x in range(3):
        for y in range(3):
            k = key(x, y)
            cells = [(i, j) for i in range(3) for j in range(3) if key(i, j) == k]
            m = sum(P[c] for c in cells)
            if m > 0:
                out[x, y] = sum(P[c]*Z[c] for c in cells)/m
    return out


def dyadic_means(n, f2=lambda a, b: (a*a + a*b + b*b)/3):
    """Group means of X(w)=w^2 on the 2**n dyadic intervals (exact formula)."""
    N = 2**n
    e = np.arange(N + 1)/N
    return e, np.array([f2(e[k], e[k+1]) for k in range(N)])
